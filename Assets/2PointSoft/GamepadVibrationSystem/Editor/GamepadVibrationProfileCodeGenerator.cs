using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using UnityEditor;

namespace TwoPointSoft.GamepadVibration.Editor
{
    public static class GamepadVibrationProfileCodeGenerator
    {
        public const string DefaultOutputPath = "Assets/GamepadVibrationGenerated/GamepadVibrationCustom.cs";
        public const string GeneratedAssemblyPath = "Assets/GamepadVibrationGenerated/TwoPointSoft.GamepadVibration.Generated.asmdef";

        private static readonly HashSet<string> Reserved = new HashSet<string>
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
            "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
            "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
            "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
            "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
            "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
            "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
            "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual",
            "void", "volatile", "while"
        };

        public static string ToIdentifier(string displayName)
        {
            if (string.IsNullOrWhiteSpace(displayName)) return "CustomProfile";
            StringBuilder result = new StringBuilder();
            bool uppercaseNext = true;
            foreach (char character in displayName.Trim())
            {
                if (!char.IsLetterOrDigit(character) && character != '_')
                {
                    uppercaseNext = true;
                    continue;
                }
                char value = uppercaseNext ? char.ToUpperInvariant(character) : character;
                if (result.Length == 0 && char.IsDigit(value)) result.Append('_');
                result.Append(value);
                uppercaseNext = false;
            }
            if (result.Length == 0) result.Append("CustomProfile");
            string identifier = result.ToString();
            if (Reserved.Contains(identifier.ToLowerInvariant())) identifier += "Profile";
            return identifier;
        }

        public static string GenerateSource(IEnumerable<GamepadVibrationProfile> sourceProfiles)
        {
            List<GamepadVibrationProfile> profiles = sourceProfiles
                .Where(profile => profile != null)
                .OrderBy(profile => string.IsNullOrWhiteSpace(profile.CodeName) ? profile.name : profile.CodeName)
                .ToList();
            HashSet<string> used = new HashSet<string>();
            StringBuilder code = new StringBuilder();
            code.AppendLine("// <auto-generated>");
            code.AppendLine("// Generated by Gamepad Vibration System. Do not edit manually.");
            code.AppendLine("// </auto-generated>");
            code.AppendLine("namespace TwoPointSoft.GamepadVibration.Generated");
            code.AppendLine("{");
            code.AppendLine("    public static class GamepadVibrationCustom");
            code.AppendLine("    {");
            foreach (GamepadVibrationProfile profile in profiles)
            {
                string baseName = ToIdentifier(string.IsNullOrWhiteSpace(profile.CodeName) ? profile.name : profile.CodeName);
                string identifier = baseName;
                int suffix = 2;
                while (!used.Add(identifier)) identifier = baseName + suffix++;
                GamepadVibrationSettings s = profile.Settings;
                code.AppendLine($"        /// <summary>{EscapeComment(profile.Description)}</summary>");
                code.AppendLine($"        public static GamepadVibrationGeneratedProfile {identifier} => new GamepadVibrationGeneratedProfile(");
                code.AppendLine($"            GamepadVibrationPlaybackMode.{profile.PlaybackMode},");
                code.AppendLine("            new GamepadVibrationSettings(");
                code.AppendLine($"                lowFrequency: {Float(s.LowFrequency)},");
                code.AppendLine($"                highFrequency: {Float(s.HighFrequency)},");
                code.AppendLine($"                duration: {Float(s.Duration)},");
                code.AppendLine($"                pulses: {s.Pulses},");
                code.AppendLine($"                interval: {Float(s.Interval)},");
                code.AppendLine($"                fadeOut: {s.FadeOut.ToString().ToLowerInvariant()},");
                code.AppendLine($"                globalIntensity: {Float(s.GlobalIntensity)}));");
                code.AppendLine();
            }
            code.AppendLine("    }");
            code.AppendLine("}");
            return code.ToString();
        }

        [MenuItem("Tools/2 Point Soft/Generate All Profiles API")]
        public static void GenerateAllFromMenu()
        {
            string path = GenerateAll();
            UnityEngine.Debug.Log("Updated custom vibration API: " + path);
        }

        public static string GenerateAll(string outputPath = DefaultOutputPath)
        {
            string[] guids = AssetDatabase.FindAssets("t:GamepadVibrationProfile");
            GamepadVibrationProfile[] profiles = guids
                .Select(guid => AssetDatabase.LoadAssetAtPath<GamepadVibrationProfile>(AssetDatabase.GUIDToAssetPath(guid)))
                .Where(profile => profile != null)
                .ToArray();
            string source = GenerateSource(profiles);
            string directory = System.IO.Path.GetDirectoryName(outputPath);
            if (!System.IO.Directory.Exists(directory)) System.IO.Directory.CreateDirectory(directory);
            System.IO.File.WriteAllText(outputPath, source, new UTF8Encoding(false));
            const string assembly = "{\n  \"name\": \"TwoPointSoft.GamepadVibration.Generated\",\n  \"rootNamespace\": \"TwoPointSoft.GamepadVibration.Generated\",\n  \"references\": [\n    \"TwoPointSoft.GamepadVibration.Runtime\"\n  ],\n  \"autoReferenced\": true,\n  \"noEngineReferences\": false\n}\n";
            System.IO.File.WriteAllText(GeneratedAssemblyPath, assembly, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(GeneratedAssemblyPath);
            AssetDatabase.ImportAsset(outputPath);
            return outputPath;
        }

        private static string Float(float value)
        {
            return value.ToString("0.0######", CultureInfo.InvariantCulture) + "f";
        }

        private static string EscapeComment(string value)
        {
            return string.IsNullOrWhiteSpace(value) ? "Custom vibration profile." : value.Replace("\r", " ").Replace("\n", " ").Replace("</", "&lt;/");
        }
    }
}
